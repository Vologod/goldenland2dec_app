import ghidra.app.script.GhidraScript;
import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileResults;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.FunctionIterator;
import java.io.File;
import java.io.FileOutputStream;
import java.io.OutputStreamWriter;
import java.io.PrintWriter;
import java.nio.charset.StandardCharsets;

public class ExportDecomp extends GhidraScript {
    @Override
    public void run() throws Exception {
        String[] args = getScriptArgs();
        if (args.length < 1) {
            println("usage: ExportDecomp <output_dir>");
            return;
        }

        File out = new File(args[0]);
        out.mkdirs();

        Address imageBase = currentProgram.getImageBase();
        DecompInterface decompiler = new DecompInterface();
        decompiler.toggleCCode(true);
        decompiler.toggleSyntaxTree(true);
        if (!decompiler.openProgram(currentProgram)) {
            println("decompiler.openProgram failed");
            return;
        }

        PrintWriter csv = new PrintWriter(new OutputStreamWriter(
            new FileOutputStream(new File(out, "functions.csv")), StandardCharsets.UTF_8));
        PrintWriter src = new PrintWriter(new OutputStreamWriter(
            new FileOutputStream(new File(out, "decompiled.c")), StandardCharsets.UTF_8));

        csv.println("rva,size,name,thunk,callers");
        src.println("/* generated by ExportDecomp.java; program=" + currentProgram.getName() + " */");

        FunctionIterator functions = currentProgram.getFunctionManager().getFunctions(true);
        int total = 0;
        int ok = 0;
        int failed = 0;
        int thunks = 0;

        while (functions.hasNext() && !monitor.isCancelled()) {
            Function function = functions.next();
            long rva = function.getEntryPoint().subtract(imageBase);
            long size = function.getBody().getNumAddresses();
            int callers = 0;
            try {
                callers = function.getCallingFunctions(monitor).size();
            } catch (Exception ignored) {
            }

            csv.println(rva + "," + size + "," + csvEscape(function.getName()) + ","
                + (function.isThunk() ? 1 : 0) + "," + callers);

            src.println();
            src.println("/* rva=0x" + Long.toHexString(rva) + " size=" + size
                + " callers=" + callers + " */");

            total++;
            if (function.isThunk()) {
                src.println("/* thunk: skipped */");
                thunks++;
            } else {
                DecompileResults result = decompiler.decompileFunction(function, 30, monitor);
                if (result != null && result.decompileCompleted()) {
                    src.println(result.getDecompiledFunction().getC());
                    ok++;
                } else {
                    String reason = result == null ? "null" : result.getErrorMessage();
                    src.println("/* decompile failed: " + reason + " */");
                    failed++;
                }
            }

            if (total % 500 == 0) {
                println("progress functions=" + total);
                csv.flush();
                src.flush();
            }
        }

        decompiler.dispose();
        csv.close();
        src.close();
        println("done functions=" + total + " ok=" + ok + " failed=" + failed + " thunks=" + thunks);
    }

    private String csvEscape(String value) {
        if (value == null) {
            return "";
        }
        if (value.indexOf(',') >= 0 || value.indexOf('"') >= 0) {
            return "\"" + value.replace("\"", "\"\"") + "\"";
        }
        return value;
    }
}
