import ghidra.app.script.GhidraScript;
import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileResults;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.Function;
import java.io.File;
import java.io.FileOutputStream;
import java.io.OutputStreamWriter;
import java.io.PrintWriter;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.List;

public class ExportNativeHandlers extends GhidraScript {
    @Override
    public void run() throws Exception {
        String[] args = getScriptArgs();
        if (args.length < 2) {
            println("usage: ExportNativeHandlers <handlers.csv> <output_dir>");
            return;
        }

        Path input = Paths.get(args[0]);
        File out = new File(args[1]);
        out.mkdirs();

        List<String> lines = Files.readAllLines(input, StandardCharsets.UTF_8);
        DecompInterface decompiler = new DecompInterface();
        decompiler.toggleCCode(true);
        decompiler.toggleSyntaxTree(true);
        if (!decompiler.openProgram(currentProgram)) {
            println("decompiler.openProgram failed");
            return;
        }

        PrintWriter csv = new PrintWriter(new OutputStreamWriter(
            new FileOutputStream(new File(out, "natives.csv")), StandardCharsets.UTF_8));
        PrintWriter src = new PrintWriter(new OutputStreamWriter(
            new FileOutputStream(new File(out, "natives.c")), StandardCharsets.UTF_8));

        csv.println("id,rva,name,created");
        src.println("/* generated by ExportNativeHandlers.java; program="
            + currentProgram.getName() + " */");

        int total = 0;
        int created = 0;
        int ok = 0;
        int failed = 0;

        for (String line : lines) {
            String trimmed = line.trim();
            if (trimmed.isEmpty() || trimmed.startsWith("#")) {
                continue;
            }
            String[] parts = trimmed.split(",");
            if (parts.length < 2) {
                continue;
            }
            long id = Long.parseLong(parts[0].trim().replace("0x", ""), 16);
            long rva = Long.parseLong(parts[1].trim().replace("0x", ""), 16);
            String name = parts.length > 2 ? parts[2].trim() : "";

            Address address = currentProgram.getImageBase().add(rva);
            Function function = getFunctionAt(address);
            boolean wasCreated = false;
            if (function == null) {
                disassemble(address);
                function = createFunction(address, "native_" + Long.toHexString(id)
                    + (name.isEmpty() ? "" : "_" + name));
                wasCreated = function != null;
                created++;
            }

            csv.println(id + ",0x" + Long.toHexString(rva) + ","
                + csvEscape(name) + "," + (wasCreated ? 1 : 0));
            src.println();
            src.println("/* id=0x" + Long.toHexString(id) + " rva=0x" + Long.toHexString(rva)
                + " name=" + name + " */");

            total++;
            if (function == null) {
                src.println("/* function could not be created */");
                failed++;
                continue;
            }

            DecompileResults result = decompiler.decompileFunction(function, 30, monitor);
            if (result != null && result.decompileCompleted()) {
                src.println(result.getDecompiledFunction().getC());
                ok++;
            } else {
                String reason = result == null ? "null" : result.getErrorMessage();
                src.println("/* decompile failed: " + reason + " */");
                failed++;
            }
        }

        decompiler.dispose();
        csv.close();
        src.close();
        println("done natives=" + total + " created=" + created + " ok=" + ok
            + " failed=" + failed);
    }

    private String csvEscape(String value) {
        if (value == null) {
            return "";
        }
        if (value.indexOf(',') >= 0 || value.indexOf('"') >= 0) {
            return "\"" + value.replace("\"", "\"\"") + "\"";
        }
        return value;
    }
}
